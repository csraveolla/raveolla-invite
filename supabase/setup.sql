CREATE OR REPLACE FUNCTION public.increment_view_count(inv_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  UPDATE public.invitations
  SET view_count = COALESCE(view_count, 0) + 1
  WHERE id = inv_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.increment_wa_terkirim(p_client_id uuid, p_jumlah int DEFAULT 1)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  UPDATE public.clients
  SET wa_terkirim = COALESCE(wa_terkirim, 0) + p_jumlah
  WHERE id = p_client_id;
END;
$$;


