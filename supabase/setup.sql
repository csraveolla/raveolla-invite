-- 1a. packages (lookup)
CREATE TABLE IF NOT EXISTS public.packages (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name        text NOT NULL UNIQUE,
  is_active   bool DEFAULT true,
  sort_order  int DEFAULT 0
);

-- 1b. clients (tenants)
CREATE TABLE IF NOT EXISTS public.clients (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nama_acara  text NOT NULL,
  token       text NOT NULL UNIQUE,
  pin_scanner text,
  base_url    text,
  paket       text DEFAULT 'lite',
  package_id  uuid REFERENCES public.packages(id) ON DELETE SET NULL,
  max_tamu    int DEFAULT 100,
  max_wa      int DEFAULT 50,
  wa_mode     text DEFAULT 'admin',
  wa_nomor    text,
  wa_api_key  text,
  wa_media_url    text,
  wa_media_nama   text,
  wa_terkirim     int DEFAULT 0,
  tanggal_acara   date,
  reminder_rsvp_aktif     bool DEFAULT false,
  reminder_rsvp_jadwal    date,
  reminder_rsvp_template  text,
  reminder_h3             bool DEFAULT false,
  reminder_h1             bool DEFAULT false,
  reminder_template_h3    text,
  reminder_template_h1    text,
  reminder_ucapan_aktif       bool DEFAULT false,
  reminder_ucapan_jadwal      date,
  reminder_ucapan_template    text,
  reminder_ucapan_target      text DEFAULT 'hadir',
  pesan_template  text,
  created_at      timestamptz DEFAULT now()
);

-- 1c. themes (lookup)
CREATE TABLE IF NOT EXISTS public.themes (
  id          int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name        text NOT NULL UNIQUE,
  theme_code  text,
  is_active   bool DEFAULT true,
  sort_order  int DEFAULT 0
);

-- 1d. invitations
CREATE TABLE IF NOT EXISTS public.invitations (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id   uuid NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
  slug        text NOT NULL UNIQUE,
  theme_id    int REFERENCES public.themes(id) ON DELETE SET NULL,
  package_id  uuid REFERENCES public.packages(id) ON DELETE SET NULL,
  is_published bool DEFAULT false,
  is_active   bool DEFAULT true,
  expired_at  timestamptz,
  section_styles jsonb DEFAULT NULL,

  bride_name      text,
  bride_nickname  text,
  bride_father    text,
  bride_mother    text,
  bride_instagram text,
  bride_photo_url text,

  groom_name      text,
  groom_nickname  text,
  groom_father    text,
  groom_mother    text,
  groom_instagram text,
  groom_photo_url text,

  quote       text,
  hashtag     text,
  music_url   text,
  view_count  int DEFAULT 0,
  created_at  timestamptz DEFAULT now()
);

-- 1e. events
CREATE TABLE IF NOT EXISTS public.events (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invitation_id   uuid NOT NULL REFERENCES public.invitations(id) ON DELETE CASCADE,
  event_name      text,
  event_date      date,
  start_time      time,
  end_time        time,
  location_name   text,
  address         text,
  maps_url        text,
  livestream_url  text,
  sort_order      int DEFAULT 0,
  custom_style    jsonb DEFAULT NULL,
  created_at      timestamptz DEFAULT now()
);

-- 1f. bank_accounts
CREATE TABLE IF NOT EXISTS public.bank_accounts (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
