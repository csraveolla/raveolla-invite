-- 1h. galleries
CREATE TABLE IF NOT EXISTS public.galleries (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invitation_id   uuid NOT NULL REFERENCES public.invitations(id) ON DELETE CASCADE,
  file_url        text,
