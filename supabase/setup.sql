-- 1g. love_stories
CREATE TABLE IF NOT EXISTS public.love_stories (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invitation_id   uuid NOT NULL REFERENCES public.invitations(id) ON DELETE CASCADE,
  event_date      date,
